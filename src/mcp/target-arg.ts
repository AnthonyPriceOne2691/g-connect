/**
 * Как называют цель на границе инструментов: alias реестра, ссылка или ID.
 *
 * Отдельным модулем, потому что этим аргументом начинаются все шесть инструментов, а
 * схема записи живёт уже в своём файле: две копии одного описания разъехались бы, и
 * модель читала бы разное в зависимости от инструмента.
 */

import { z } from 'zod';

export const targetArg = z.string().min(1).describe('alias из реестра, ссылка на файл или его ID');

/**
 * Лист таблицы — общий у чтения и записи (Q27): без него берётся вкладка из ссылки (gid), затем
 * лист реестра, затем первый. Одно описание на два инструмента — по той же причине, что `targetArg`.
 */
export const sheetArg = z
  .string()
  .min(1)
  .optional()
  .describe('Таблица: имя листа; без него — вкладка из ссылки (gid), лист реестра или первый');
