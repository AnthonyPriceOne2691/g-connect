/**
 * Загрузка локального файла на Drive (D-27, Q45–Q48) на внешней границе ядра.
 *
 * Отдельным модулем по гейту длины `ops.ts`. Цель — папка: файл ляжет новым, а одноимённый файл
 * папки получит свежую версию (решение владельца 2026-11-09 «не плодим копии»). С `replace` цель —
 * сам файл: его содержимое заменяется новой ревизией, ID и ссылка у команды те же.
 *
 * zod — подмножество, общее у v3 и v4: проект переходит на v4 параллельно.
 */

import { z } from 'zod';

import { commonFields } from '../op-fields.js';

export const uploadFileOp = z.object({
  op: z.literal('uploadFile'),
  /** Путь к файлу: абсолютный или от каталога проекта сессии — судит `vetLocalFile`. */
  localPath: z.string().min(1),
  /** Имя на Диске; без него — имя локального файла. По нему ищется одноимённый файл папки. */
  name: z.string().min(1).optional(),
  /** `target` — сам файл: заменить его содержимое новой ревизией вместо загрузки в папку. */
  replace: z.boolean().default(false),
  ...commonFields,
});
